import Foundation
import SwiftUI

public struct BackupData: Codable, Sendable {
    public let formulae: [String]
    public let casks: [String]
    public let timestamp: Date
    
    public init(formulae: [String], casks: [String], timestamp: Date = Date()) {
        self.formulae = formulae
        self.casks = casks
        self.timestamp = timestamp
    }
}

public class BackupManager {
    public static func export(formulae: [String], casks: [String], to url: URL) throws {
        let data = BackupData(formulae: formulae, casks: casks, timestamp: Date())
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        let jsonData = try encoder.encode(data)
        try jsonData.write(to: url)
    }
    
    public static func load(from url: URL) throws -> BackupData {
        let data = try Data(contentsOf: url)
        let decoder = JSONDecoder()
        return try decoder.decode(BackupData.self, from: data)
    }
    
    public static func exportBrewfile(formulae: [String], casks: [String], to url: URL) throws {
        var lines: [String] = []
        lines.append("# Brewfile generated by TerminalManager at \(Date())")
        lines.append("")
        if !casks.isEmpty {
            lines.append("# Casks")
            for cask in casks.sorted() {
                lines.append("cask \"\(cask)\"")
            }
            lines.append("")
        }
        if !formulae.isEmpty {
            lines.append("# Formulae")
            for formula in formulae.sorted() {
                lines.append("brew \"\(formula)\"")
            }
            lines.append("")
        }
        let content = lines.joined(separator: "\n")
        try content.write(to: url, atomically: true, encoding: .utf8)
    }
}
